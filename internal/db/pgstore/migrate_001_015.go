// latestSchemaVersion is the highest version the PostgreSQL migrations reach.
// The version numbers are the SQLite store's: version N here has the tables
// and columns of a fresh SQLite database migrated to N.
const latestSchemaVersion = 15

// migrations are keyed by the version they migrate TO, as in the SQLite store.
// Version 1 is the SQLite schemaDDL, which creates its tables in their current
// shape (issues and labels already carry project_id, and labels its
// per-project UNIQUE), so later migrations skip what it already made.
//
// Every migration is re-runnable against a database that already has its
// effect: CREATE ... IF NOT EXISTS, ADD COLUMN IF NOT EXISTS, and inserts that
// do nothing on conflict. SQLite needs a column probe before each ALTER for
// the same property.
var migrations = map[int]func(context.Context, *sql.Tx) error{
	1:  execMigration(v1DDL),
	2:  execMigration(v2DDL),
	3:  execMigration(v3DDL),
	4:  execMigration(v4DDL),
	5:  execMigration(v5DDL),
	6:  execMigration(v6DDL),
	7:  execMigration(v7DDL),
	8:  execMigration(v8DDL),
	9:  migrateV8ToV9,
	10: execMigration(v10DDL),
	11: execMigration(v11DDL),
	12: execMigration(v12DDL),
	13: execMigration(v13DDL),
	14: execMigration(v14DDL),
	15: execMigration(v15DDL),
}

// Migrate brings the database from the version its meta table records (0 when
// it has none) to latestSchemaVersion, and refuses a database stamped by a
// newer binary.
func Migrate(ctx context.Context, db *sql.DB) error {
	stored, err := schemaVersion(ctx, db)
	if err != nil {
		return err
	}
	if stored > latestSchemaVersion {
		return fmt.Errorf(
			"store schema version %d is newer than this binary supports (%d); upgrade docket to open it",
			stored, latestSchemaVersion)
	}
	return applyMigrations(ctx, db, stored, latestSchemaVersion)
}

// applyMigrations runs migrations from+1 through to, each in its own
// transaction that also stamps its version.
func applyMigrations(ctx context.Context, db *sql.DB, from, to int) error {
	for v := from + 1; v <= to; v++ {
		migrate, ok := migrations[v]
		if !ok {
			return fmt.Errorf("missing postgres migration for version %d", v)
		}
		if err := applyMigration(ctx, db, v, migrate); err != nil {
			return err
		}
	}
	return nil
}

func applyMigration(ctx context.Context, db *sql.DB, v int, migrate func(context.Context, *sql.Tx) error) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("beginning postgres migration %d: %w", v, err)
	}
	defer tx.Rollback()

	if err := migrate(ctx, tx); err != nil {
		return fmt.Errorf("applying postgres migration %d: %w", v, err)
	}
	if _, err := tx.ExecContext(ctx,
		`INSERT INTO meta (key, value) VALUES ('schema_version', $1)
		 ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value`,
		strconv.Itoa(v),
	); err != nil {
		return fmt.Errorf("stamping postgres schema version %d: %w", v, err)
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("committing postgres migration %d: %w", v, err)
	}
	return nil
}

// schemaVersion reads the stamped version, or 0 for a database without a meta
// table or without a stamp in it.
func schemaVersion(ctx context.Context, db *sql.DB) (int, error) {
	var hasMeta bool
	if err := db.QueryRowContext(ctx, `SELECT to_regclass('meta') IS NOT NULL`).Scan(&hasMeta); err != nil {
		return 0, fmt.Errorf("probing for the meta table: %w", err)
	}
	if !hasMeta {
		return 0, nil
	}
	var value string
	err := db.QueryRowContext(ctx, `SELECT value FROM meta WHERE key = 'schema_version'`).Scan(&value)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, nil
	}
	if err != nil {
		return 0, fmt.Errorf("reading schema version: %w", err)
	}
	v, err := strconv.Atoi(value)
	if err != nil {
		return 0, fmt.Errorf("parsing schema version %q: %w", value, err)
	}
	return v, nil
}

// execMigration runs a migration's SQL as one multi-statement batch; pgx sends
// a call without arguments over the simple protocol, which accepts several
// statements.
func execMigration(ddl string) func(context.Context, *sql.Tx) error {
	return func(ctx context.Context, tx *sql.Tx) error {
		_, err := tx.ExecContext(ctx, ddl)
		return err
	}
}

