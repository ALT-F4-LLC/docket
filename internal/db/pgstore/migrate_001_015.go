// v8DDL ports migrateV7ToV8, including its backfill of steps.gate_trail into
// gate_results: one stub row per trail element with ordinal = array index
// (G1, G2), idempotent through the identity index (G4), and one unmatched row
// for a trail that is not an array (G5). jsonb admits no unparseable trail, so
// "not an array" is the remaining malformed case.
const v8DDL = `
CREATE TABLE IF NOT EXISTS gate_results (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	run_id        BIGINT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
	step_id       BIGINT NOT NULL REFERENCES steps(id) ON DELETE CASCADE,
	gate          TEXT   NOT NULL,
	ordinal       BIGINT NOT NULL DEFAULT 0,
	argv          JSONB,
	exit          BIGINT,
	duration_ms   BIGINT NOT NULL DEFAULT 0,
	output        TEXT   NOT NULL DEFAULT '',
	truncated     BIGINT NOT NULL DEFAULT 0,
	verdict       TEXT   NOT NULL,
	pre           BIGINT NOT NULL DEFAULT 0,
	stub          BIGINT NOT NULL DEFAULT 0,
	stub_entry    BIGINT NOT NULL DEFAULT 0,
	reason        TEXT,
	created_at_ms BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_gate_results_step ON gate_results(step_id);
CREATE INDEX IF NOT EXISTS idx_gate_results_run ON gate_results(run_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_gate_results_identity
	ON gate_results(step_id, gate, ordinal);

CREATE TABLE IF NOT EXISTS trust_cache (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	run_id        BIGINT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
	gate          TEXT   NOT NULL,
	argv_sha256   TEXT   NOT NULL,
	entry_name    TEXT   NOT NULL,
	matched       BIGINT NOT NULL,
	prefix        BIGINT NOT NULL DEFAULT 0,
	at_ms         BIGINT NOT NULL,
	UNIQUE(run_id, gate, argv_sha256, at_ms)
);

INSERT INTO gate_results
	(run_id, step_id, gate, ordinal, argv, exit, duration_ms, output,
	 truncated, verdict, pre, stub, created_at_ms)
SELECT s.run_id, s.id,
       COALESCE(r.value->>'gate', ''),
       r.ordinal - 1,
       NULLIF(r.value->'argv', 'null'::jsonb),
       COALESCE((r.value->>'exit')::BIGINT, 0),
       COALESCE((r.value->>'duration_ms')::BIGINT, 0),
       COALESCE(r.value->>'output', ''),
       CASE WHEN (r.value->>'truncated')::BOOLEAN THEN 1 ELSE 0 END,
       COALESCE(r.value->>'verdict', ''),
       0, 1, s.updated_at_ms
  FROM steps s
 CROSS JOIN LATERAL jsonb_array_elements(
       CASE WHEN jsonb_typeof(s.gate_trail) = 'array' THEN s.gate_trail ELSE '[]'::jsonb END
       ) WITH ORDINALITY AS r(value, ordinal)
ON CONFLICT (step_id, gate, ordinal) DO NOTHING;

INSERT INTO gate_results
	(run_id, step_id, gate, ordinal, verdict, stub, reason, created_at_ms)
SELECT run_id, id, '', 0, 'unmatched', 1, 'gate trail is not a JSON array', updated_at_ms
  FROM steps
 WHERE jsonb_typeof(gate_trail) NOT IN ('array', 'null')
ON CONFLICT (step_id, gate, ordinal) DO NOTHING;
`

