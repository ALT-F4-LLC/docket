// migrateV8ToV9 ports the SQLite migration: v9DDL, then the builtin
// aggregate@1 seed, which does nothing when the row exists.
func migrateV8ToV9(ctx context.Context, tx *sql.Tx) error {
	if _, err := tx.ExecContext(ctx, v9DDL); err != nil {
		return err
	}

	body := schema.AggregateBody()
	index, err := schema.DeriveIndex(body)
	if err != nil {
		return fmt.Errorf("the embedded %s document is unusable: %w", schema.AggregateRef(), err)
	}
	ordered, err := json.Marshal(index)
	if err != nil {
		return fmt.Errorf("encoding the builtin's ordered index: %w", err)
	}
	if _, err := tx.ExecContext(ctx,
		`INSERT INTO schemas
		   (name, version, source_path, source_sha256, body, ordered, builtin,
		    created_at_ms, row_version)
		 VALUES ($1, $2, NULL, $3, $4, $5, 1, $6, 1)
		 ON CONFLICT DO NOTHING`,
		schema.AggregateName, schema.AggregateVersion, schema.AggregateSHA256(),
		string(body), string(ordered), model.NowMS(),
	); err != nil {
		return fmt.Errorf("seeding %s: %w", schema.AggregateRef(), err)
	}
	return nil
}

