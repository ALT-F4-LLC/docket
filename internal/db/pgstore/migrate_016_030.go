// v24DDL ports migrateV23ToV24.
const v24DDL = `
CREATE TABLE IF NOT EXISTS gate_override_grants (
	id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	run_id         BIGINT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
	origin_step_id BIGINT NOT NULL REFERENCES steps(id) ON DELETE CASCADE,
	gate           TEXT   NOT NULL,
	exit           BIGINT,
	reason         TEXT   NOT NULL DEFAULT '',
	note           TEXT   NOT NULL DEFAULT '',
	covered_steps  BIGINT NOT NULL DEFAULT 0,
	created_at_ms  BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_gate_override_grants_run
	ON gate_override_grants(run_id);
`

