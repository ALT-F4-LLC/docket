// v22DDL ports migrateV21ToV22, including its back-fill: a parked run with a
// budget breach was parked by the budget, and a parked run with no breach and
// no parked step was parked by its operator. The literals are the
// model.RunWaitingHuman, model.RunPauseOrigin* and db.StepWaitingHuman values
// the SQLite migration binds. Both updates touch only rows still holding the
// empty default, so a rerun changes nothing.
const v22DDL = `
ALTER TABLE runs ADD COLUMN IF NOT EXISTS pause_origin TEXT NOT NULL DEFAULT '';

UPDATE runs
   SET pause_origin = 'budget'
 WHERE status = 'waiting-human' AND pause_origin = ''
   AND breach_reason IS NOT NULL AND breach_reason <> '';

UPDATE runs
   SET pause_origin = 'operator'
 WHERE status = 'waiting-human' AND pause_origin = ''
   AND id NOT IN (SELECT run_id FROM steps WHERE status = 'waiting-human');
`

