// Several of these columns already exist on a PostgreSQL store, because v1 and
// v7 create issues, runs, steps and gate_results in their current shape, as
// SQLite's own DDL does. Their ADD COLUMN IF NOT EXISTS is then a no-op, again
// as in SQLite, where the migration probes the column first.

